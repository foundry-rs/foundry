// Generate the client embedded in Forge without adding Node to Cargo builds.
import { build } from "esbuild";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { isBuiltin } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync, gzipSync } from "node:zlib";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes("--check");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/extension.ts"],
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  external: ["vscode"],
  minify: true,
  legalComments: "inline",
  metafile: true,
  write: false,
  logLevel: "silent",
});

if (result.warnings.length > 0) {
  throw new Error(`Unexpected bundle warnings: ${JSON.stringify(result.warnings)}`);
}
for (const output of Object.values(result.metafile.outputs)) {
  for (const dependency of output.imports) {
    if (dependency.external && dependency.path !== "vscode" && !isBuiltin(dependency.path)) {
      throw new Error(`Unbundled runtime dependency: ${dependency.path}`);
    }
  }
}

// Attribute only packages included in the generated runtime, including transitive dependencies.
const packagePaths = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const segments = input.replaceAll("\\", "/").split("/");
  const index = segments.lastIndexOf("node_modules");
  if (index !== -1) {
    const count = segments[index + 1].startsWith("@") ? 3 : 2;
    packagePaths.add(segments.slice(0, index + count).join("/"));
  }
}
const notices = [
  "Third-party notices for the Forge-embedded VS Code client.",
  "Generated by npm run bundle; do not edit by hand.",
];
for (const packagePath of [...packagePaths].sort()) {
  const directory = join(root, packagePath);
  const manifest = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
  const licenses = (await readdir(directory))
    .filter((name) => /^(licen[sc]e|copying|notice)(?:[.-]|$)/i.test(name))
    .sort();
  if (licenses.length === 0) {
    throw new Error(`Missing license text for bundled package ${manifest.name}`);
  }
  notices.push("", "=".repeat(72), `${manifest.name} ${manifest.version} (${manifest.license})`);
  for (const license of licenses) {
    const text = (await readFile(join(directory, license), "utf8")).replaceAll("\r\n", "\n").trimEnd();
    notices.push("", `${license}:`, "", text);
  }
}

const javascript = Buffer.from(result.outputFiles[0].contents);
const compressed = gzipSync(javascript, { level: 9 });
// Set the gzip OS field to unspecified so host platforms produce the same header.
compressed[9] = 255;
const artifacts = [
  ["extension.js.gz", compressed],
  ["THIRD_PARTY_NOTICES.txt", Buffer.from(notices.join("\n") + "\n")],
];
if (!check) {
  await mkdir(join(root, "dist"), { recursive: true });
}
for (const [name, contents] of artifacts) {
  const destination = join(root, "dist", name);
  if (check) {
    const existing = await readFile(destination);
    // Different Node zlib versions may encode identical JavaScript differently.
    const equal = name.endsWith(".gz")
      ? gunzipSync(existing).equals(javascript)
      : existing.equals(contents);
    if (!equal) {
      throw new Error(`${name} is stale; run npm run bundle and commit the generated files.`);
    }
  } else {
    await writeFile(destination, contents);
  }
}
console.log(`${check ? "Checked" : "Generated"} embedded client: ${javascript.length} bytes, ${compressed.length} bytes gzipped; ${packagePaths.size} dependency licenses.`);
