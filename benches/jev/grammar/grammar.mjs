// Typed generation for the checked-in local ledger model. No Solidity from model responses is emitted.
export const MODEL = 'typesafe/jev-1.13'
export const VERSION = 1
export const PRODUCTIONS = {
  action: {
    deposit: 'Move free balance into the deposit.',
    withdraw: 'Move deposited balance back into free balance.'
  },
  amount: {
    uint: 'A uint256 argument generated by Forge at runtime.',
    balance: 'Read ledger.balanceOf(address) immediately before this action.',
    deposited: 'Read ledger.depositedBalanceOf(address) immediately before this action.'
  },
  address: { bytes20: 'An arbitrary bytes20 argument generated by Forge.', sender: 'The sender of this action.' },
  sender: { one: 'address(0x1)', two: 'address(0x2)', three: 'address(0x3)' }
}
const ACTORS = { one: 1, two: 2, three: 3 }

export function settings(input = {}) {
  const value = { seed: 1, sequences: 2, length: 3, exploration: 0.2, ...input }
  if (!Number.isInteger(value.seed) || value.seed < 0 || value.seed > 0xffffffff) throw new Error('seed must be uint32')
  for (const key of ['sequences', 'length'])
    if (!Number.isInteger(value[key]) || value[key] < 1 || value[key] > 8) throw new Error(`${key} must be in 1..8`)
  if (!Number.isFinite(value.exploration) || value.exploration < 0 || value.exploration > 1)
    throw new Error('exploration must be in 0..1')
  return value
}

export function randomSource(seed) {
  let state = seed >>> 0
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let value = Math.imul(state ^ (state >>> 15), state | 1)
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61)
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296
  }
}

export function requestFor(prefix, sequence, step) {
  return {
    model: MODEL,
    state: {
      model:
        'LocalLedger: three actors start with 1000 free units each and zero deposits. Deposit moves free to deposited; withdraw reverses it. Excess amounts revert without changing state. No fees or external assets.',
      prefix,
      sequence,
      step,
      goal:
        'Exercise diverse valid accounting transitions and input boundaries. Prefix is syntax only: actual balances and fuzzed operands are unknown until Forge executes the program.'
    },
    questions: Object.fromEntries(
      Object.entries(PRODUCTIONS).map(([symbol, criteria]) => [symbol, {
        type: 'choice',
        instructions:
          `Select a useful ${symbol} production for the next action. Your siblings are selected independently; do not assume their answers.`,
        criteria
      }])
    )
  }
}

export function validateAnswers(response) {
  if (typeof response?.model !== 'string' || (response.model !== MODEL && !response.model.startsWith(`${MODEL}-`)))
    throw new Error('Unexpected model')
  if (!response.answers || Object.keys(response.answers).length !== Object.keys(PRODUCTIONS).length)
    throw new Error('Expected one answer for each grammar nonterminal')
  for (const [symbol, productions] of Object.entries(PRODUCTIONS)) {
    const answer = response.answers[symbol]
    const keys = Object.keys(productions)
    if (answer?.type !== 'choice' || !keys.includes(answer.choice)) throw new Error(`Invalid ${symbol} choice`)
    if (!answer.probabilities || Object.keys(answer.probabilities).length !== keys.length)
      throw new Error(`Invalid ${symbol} probabilities`)
    const weights = keys.map(key => answer.probabilities[key])
    if (
      weights.some(weight => typeof weight !== 'number' || !Number.isFinite(weight) || weight < 0 || weight > 1)
      || Math.abs(weights.reduce((a, b) => a + b, 0) - 1) > 0.01
    ) {
      throw new Error(`Invalid ${symbol} probabilities`)
    }
  }
  return response.answers
}

export function uniformAnswers() {
  return Object.fromEntries(
    Object.entries(PRODUCTIONS).map(([symbol, productions]) => {
      const keys = Object.keys(productions)
      return [symbol, {
        type: 'choice',
        choice: keys[0],
        probabilities: Object.fromEntries(keys.map(key => [key, 1 / keys.length]))
      }]
    })
  )
}

export function sample(symbol, answer, draw, exploration) {
  if (!Number.isFinite(draw) || draw < 0 || draw >= 1) throw new Error('Invalid random draw')
  const keys = Object.keys(PRODUCTIONS[symbol])
  const sum = keys.reduce((total, key) => total + answer.probabilities[key], 0)
  let cumulative = 0
  for (const key of keys) {
    cumulative += (1 - exploration) * answer.probabilities[key] / sum + exploration / keys.length
    if (draw < cumulative) return key
  }
  return keys.at(-1)
}

export function statement(choices) {
  for (const [symbol, productions] of Object.entries(PRODUCTIONS))
    if (!Object.hasOwn(productions, choices[symbol])) throw new Error(`Invalid ${symbol} production`)
  const amount = choices.amount === 'uint'
    ? { kind: 'uint' }
    : { kind: choices.amount, address: { kind: choices.address } }
  return { action: choices.action, sender: ACTORS[choices.sender], amount }
}

function exactKeys(value, keys) {
  return value && typeof value === 'object' && !Array.isArray(value)
    && Object.keys(value).length === keys.length && keys.every(key => Object.hasOwn(value, key))
}

export function validatePrograms(programs) {
  if (!Array.isArray(programs) || programs.length < 1 || programs.length > 8) throw new Error('Invalid program count')
  for (const program of programs) {
    if (!Array.isArray(program) || program.length < 1 || program.length > 8) throw new Error('Invalid sequence length')
    for (const node of program) {
      if (
        !exactKeys(node, ['action', 'sender', 'amount']) || !['deposit', 'withdraw'].includes(node.action)
        || ![1, 2, 3].includes(node.sender)
      ) { throw new Error('Invalid action node') }
      const amount = node.amount
      if (amount?.kind === 'uint') {
        if (!exactKeys(amount, ['kind'])) throw new Error('Invalid uint node')
      } else if (['balance', 'deposited'].includes(amount?.kind)) {
        if (
          !exactKeys(amount, ['kind', 'address']) || !exactKeys(amount.address, ['kind'])
          || !['sender', 'bytes20'].includes(amount.address.kind)
        ) { throw new Error('Invalid balance node') }
      } else { throw new Error('Invalid amount node') }
    }
  }
}

export async function generate(options, decide, record = async () => {}) {
  const config = settings(options)
  const random = randomSource(config.seed)
  const programs = []
  for (let sequence = 0; sequence < config.sequences; sequence++) {
    const program = []
    for (let step = 0; step < config.length; step++) {
      const request = requestFor(structuredClone(program), sequence, step)
      const response = await decide(request)
      // Persist a successful response before validation or any subsequent paid request.
      await record(request, response)
      const answers = validateAnswers(response)
      const choices = Object.fromEntries(
        Object.keys(PRODUCTIONS).map(symbol => [symbol, sample(symbol, answers[symbol], random(), config.exploration)])
      )
      program.push(statement(choices))
    }
    programs.push(program)
  }
  validatePrograms(programs)
  return programs
}

export function emitHandler(programs) {
  validatePrograms(programs)
  const functions = programs.map((program, sequence) => {
    const actions = program.map((node, index) => {
      let expression = `rawAmounts[${index}]`
      if (node.amount.kind !== 'uint') {
        const owner = node.amount.address.kind === 'sender' ? 'sender' : `address(uint160(rawAddresses[${index}]))`
        const view = node.amount.kind === 'balance' ? 'balanceOf' : 'depositedBalanceOf'
        expression = `ledger.${view}(${owner})`
      }
      return `        {
            address sender = address(uint160(${node.sender}));
            uint256 amount = ${expression};
            _action(${node.action === 'withdraw'}, sender, amount);
        }`
    }).join('\n')
    // Full-width ABI carriers let corpus mutation vary all bits without violating bytes20 padding.
    return `    function sequence${sequence}(uint256[${program.length}] calldata rawAmounts, uint256[${program.length}] calldata rawAddresses) external {
${actions}
    }`
  }).join('\n\n')
  return `// SPDX-License-Identifier: MIT
pragma solidity =0.8.30;
import {LocalLedger, GrammarHandlerBase} from "./Model.sol";

/// Generated from a validated typed AST. View expressions stay live at each call site.
contract GeneratedHandler is GrammarHandlerBase {
    constructor(LocalLedger ledger_) GrammarHandlerBase(ledger_) {}

${functions}
}
`
}

export function emitSuite(programs) {
  validatePrograms(programs)
  const selectors = programs.map((_, index) =>
    `        selectors[${index + 2}] = GeneratedHandler.sequence${index}.selector;`
  ).join('\n')
  return `// SPDX-License-Identifier: MIT
pragma solidity =0.8.30;
import {LocalLedger, GrammarHandlerBase} from "../src/Model.sol";
import {GeneratedHandler} from "../src/GeneratedHandler.sol";

contract GeneratedInvariantTest {
    struct FuzzSelector { address addr; bytes4[] selectors; }
    LocalLedger private ledger;
    GeneratedHandler private handler;

    function setUp() public {
        ledger = new LocalLedger();
        handler = new GeneratedHandler(ledger);
    }

    function targetContracts() public view returns (address[] memory targets) {
        targets = new address[](1);
        targets[0] = address(handler);
    }

    function targetSelectors() public view returns (FuzzSelector[] memory targets) {
        bytes4[] memory selectors = new bytes4[](${programs.length + 2});
        selectors[0] = GrammarHandlerBase.depositRaw.selector;
        selectors[1] = GrammarHandlerBase.withdrawRaw.selector;
${selectors}
        targets = new FuzzSelector[](1);
        targets[0] = FuzzSelector(address(handler), selectors);
    }

    function invariant_conservation() public view {
        for (uint160 actor = 1; actor <= 3; actor++) {
            address owner = address(actor);
            require(ledger.balanceOf(owner) + ledger.depositedBalanceOf(owner) == 1000, "conservation");
        }
    }
}
`
}

